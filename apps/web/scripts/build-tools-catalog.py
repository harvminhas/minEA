#!/usr/bin/env python3
"""Regenerate lib/catalog/tools.json and tools-catalog.ts from the 26 hand-kept entries plus
scripts/tools-data.txt (Name|aliases|Vendor|Category|hosting s/p/o/e/d|kind a/p/s|ssoUsual 1/0).
New entries carry typicalAnnual null: no list-price estimate is invented."""
import json
from pathlib import Path

WEB = Path(__file__).resolve().parents[1]
CORE = json.loads((WEB / "scripts/tools-core.json").read_text())
H = {"s": "saas", "p": "paas", "o": "own", "e": "either", "d": "desktop"}
K = {"a": "app", "p": "platform", "s": "server"}

def norm(v):
    import re
    return re.sub(r"[^a-z0-9]+", " ", v.lower()).strip()

# Extra spellings for the hand-kept entries. Only aliases are appended; their other values stay as they were.
EXTRA_ALIASES = {
    "Salesforce": ["sales force", "salesforce crm", "salesforce sales cloud", "sales cloud"],
    "QuickBooks Online": ["quick books", "quickbooks onine"],
    "Microsoft 365": ["o365", "ms365", "ms 365", "office365"],
    "Zoom Workplace": ["zoom meetings"],
    "Oracle NetSuite": ["net suite"],
    "HubSpot": ["hub spot", "hubspot crm"],
    "Google Workspace": ["google apps"],
    "Microsoft Entra ID": ["aad"],
}
CORE = [{**t, "aliases": t["aliases"] + [a for a in EXTRA_ALIASES.get(t["name"], []) if a not in t["aliases"]]} for t in CORE]
tools = list(CORE)
seen = {norm(n) for t in CORE for n in [t["name"], *t["aliases"]]}
for line in (WEB / "scripts/tools-data.txt").read_text().splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    name, aliases, vendor, category, host, kind, sso = line.split("|")
    if norm(name) in seen:
        continue
    names = [a.strip() for a in aliases.split(",") if a.strip()]
    keep = []
    for a in names:
        if norm(a) in seen or norm(a) == norm(name) and a.lower() in keep:
            continue
        keep.append(a.lower())
    seen.update({norm(name), *map(norm, keep)})
    entry = {"name": name, "aliases": keep, "vendor": vendor, "category": category,
             "hosting": H[host], "kind": K[kind], "typicalAnnual": None, "unit": "year"}
    if sso == "1":
        entry["ssoUsual"] = True
    tools.append(entry)

(WEB / "lib/catalog/tools.json").write_text(json.dumps(tools, indent=1) + "\n")
rows = ",\n".join("  " + json.dumps(t, separators=(",", ":")) for t in tools)
(WEB / "lib/catalog/tools-catalog.ts").write_text(
    "/** Same list as tools.json (generated by scripts/build-tools-catalog.py). The unit runner cannot\n"
    " * import JSON, so the app reads this module. */\n"
    f"export const TOOL_CATALOG = [\n{rows},\n];\n"
)
print(len(tools), "tools")
